#!/bin/bash
# Usage: scripts/debian-defconfig.sh <version> [debian-config]
#
# Generates linux-<version>/arch/riscv/configs/k1_amdgpu_debian_defconfig: the Debian
# riscv64 kernel config (default: newest configs/debian/config-*, see
# fetch-debian-config.sh) adapted to the Milk-V Jupiter:
#   - the other RISC-V platforms are switched off (drivers that only exist for those
#     SoCs drop out with them); ARCH_SPACEMIT and the generic ARCH_VIRT stay on;
#   - our own release name and module signing with a key generated at build time
#     (Debian signs its modules afterwards with its own key);
#   - cpufreq governor performance by default (schedutil made the K1 crash at boot);
#   - options that are new in <version> get their default value (olddefconfig).
# Commit the result in linux-<version>/ and run `make export-<version>`.
set -euo pipefail

V=${1:?usage: $0 <version> [debian-config]}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
DEBCFG=${2:-$(ls "$ROOT"/configs/debian/config-* | sort -V | tail -1)}
TREE=$ROOT/linux-$V
B=$ROOT/build/$V-debian/obj
OUT=$TREE/arch/riscv/configs/k1_amdgpu_debian_defconfig
KMAKE=(make -s -C "$TREE" O="$B" ARCH=riscv CROSS_COMPILE="${CROSS_COMPILE:-riscv64-linux-gnu-}" LOCALVERSION=)

# Other RISC-V SoC families (arch/riscv/Kconfig.socs) that Debian enables
OTHER_SOCS="ARCH_ANDES ARCH_ANLOGIC ARCH_CANAAN ARCH_ESWIN ARCH_MICROCHIP
	ARCH_MICROCHIP_POLARFIRE ARCH_RENESAS ARCH_SIFIVE ARCH_SOPHGO ARCH_STARFIVE
	SOC_STARFIVE ARCH_SUNXI ARCH_TENSTORRENT ARCH_THEAD ARCH_ULTRARISC"

[ -e "$TREE/.git" ] || { echo "no kernel tree $TREE (make checkout-$V)" >&2; exit 1; }
echo ">> starting from $(basename "$DEBCFG")"
mkdir -p "$B"
cp "$DEBCFG" "$B/.config"

cfg() { "$TREE/scripts/config" --file "$B/.config" "$@"; }
for s in $OTHER_SOCS; do cfg -d "$s"; done
cfg -e ARCH_SPACEMIT -e ARCH_VIRT \
	--set-str LOCALVERSION "-k1-amdgpu-debian" -d LOCALVERSION_AUTO \
	-e MODULE_SIG -e MODULE_SIG_ALL --set-str MODULE_SIG_KEY "certs/signing_key.pem" \
	--set-str SYSTEM_TRUSTED_KEYS ""
# Fedora's cross gcc supports plugins, Debian's build does not use them
cfg -d GCC_PLUGINS
# Default cpufreq governor performance instead of Debian's schedutil: with schedutil
# the K1 crashed sporadically during boot (wild pointers, SIGILL, a kernel Oops on a
# valid mapping) in ~25% of the boots; with performance (as in the modules flavor) it
# never did. See milk-v-testing.md, step 18. schedutil stays available at runtime.
cfg -d CPU_FREQ_DEFAULT_GOV_SCHEDUTIL -e CPU_FREQ_DEFAULT_GOV_PERFORMANCE
command -v pahole >/dev/null ||
	echo ">> warning: no pahole (dwarves): BTF, sched_ext and other BPF options will be missing" >&2
"${KMAKE[@]}" olddefconfig

# Sanity check: board essentials must have survived
missing=
for s in ARCH_SPACEMIT SIFIVE_PLIC PCIE_SPACEMIT_K1 PHY_SPACEMIT_K1_PCIE PHY_SPACEMIT_K1_USB2 \
	USB_DWC3 USB_DWC3_GENERIC_PLAT USB_ONBOARD_DEV MMC_SDHCI_OF_K1 SPACEMIT_K1_EMAC \
	SPACEMIT_K1_CCU PINCTRL_SPACEMIT_K1 MFD_SPACEMIT_P1 DRM_AMDGPU DRM_AMDGPU_CIK; do
	grep -qE "^CONFIG_$s=[ym]$" "$B/.config" || missing="$missing $s"
done
[ -z "$missing" ] || { echo "missing board options:$missing" >&2; exit 1; }

"${KMAKE[@]}" savedefconfig
{
	cat <<-EOF
	# Milk-V Jupiter (SpacemiT K1) with an AMD GPU, based on the Debian riscv64 kernel
	# config ($(basename "$DEBCFG")): everything Debian enables, minus the
	# other RISC-V SoC families, plus our release name, module signing and the
	# performance cpufreq governor (schedutil made the K1 crash during boot).  Options
	# that are newer than that Debian kernel have their default value.
	# Generated by scripts/debian-defconfig.sh; needs an initramfs, firmware comes
	# from /lib/firmware (e.g. Debian package firmware-amd-graphics).
	EOF
	cat "$B/defconfig"
	# BTF needs pahole on the build host; without it Kconfig drops these silently
	for s in DEBUG_INFO_BTF DEBUG_INFO_BTF_MODULES; do
		if grep -qx "CONFIG_$s=y" "$DEBCFG" && ! grep -qx "CONFIG_$s=y" "$B/.config"; then
			echo "CONFIG_$s=y"
			echo ">> warning: $s needs pahole (dwarves); kept in the defconfig" >&2
		fi
	done
} >"$OUT"
echo ">> $OUT ($(wc -l <"$OUT") lines)"
